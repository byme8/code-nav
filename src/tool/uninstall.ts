import { existsSync, lstatSync, readFileSync, readdirSync, rmdirSync, rmSync, writeFileSync } from "node:fs";
import { homedir, tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { removePermission, stopAllDaemons } from "./install-global.ts";
import { EXIT } from "./output.ts";
import { EXE_SUFFIX } from "./platform.ts";
import { cacheRoot, cargoHome } from "./rust-src.ts";

export const UNINSTALL_USAGE = "usage: code-nav uninstall [--bin-dir <dir>] [--claude-home <dir>]";
const SKILL_MARKER = "<!-- Generated by `bun src/tool/install-global.ts`";

type Out = (text: string) => void;

function parseArgs(argv: string[]): { binDir: string; claudeHome: string } | null {
  let binDir = join(homedir(), ".local", "bin");
  let claudeHome = join(homedir(), ".claude");
  for (let i = 0; i < argv.length; i += 2) {
    const value = argv[i + 1];
    if (value === undefined || value === "") return null;
    if (argv[i] === "--bin-dir") binDir = resolve(value);
    else if (argv[i] === "--claude-home") claudeHome = resolve(value);
    else return null;
  }
  return { binDir, claudeHome };
}

function remove(path: string, what: string, out: Out): boolean {
  if (!existsSync(path)) return true;
  try {
    rmSync(path, { recursive: true, force: true, maxRetries: 10, retryDelay: 100 });
    out(`removed ${what}: ${path}`);
    return true;
  } catch (e) {
    out(`error: ${what} not removed: ${path} (${(e as Error).message})`);
    return false;
  }
}

function removeIfEmpty(dir: string): void {
  try {
    if (readdirSync(dir).length === 0) rmdirSync(dir);
  } catch {
    return;
  }
}

function removeFile(path: string, what: string, out: Out): boolean {
  let entry;
  try {
    entry = lstatSync(path);
  } catch {
    return true;
  }
  if (!entry.isFile() && !entry.isSymbolicLink()) {
    out(`kept ${what}: ${path} (not a file)`);
    return true;
  }
  return remove(path, what, out);
}

function removeCache(out: Out): boolean {
  const root = cacheRoot();
  const ok = remove(join(root, "rust-src"), "cache", out);
  removeIfEmpty(root);
  return ok;
}

function removeSkill(skillDir: string, out: Out): boolean {
  const skill = join(skillDir, "SKILL.md");
  if (!existsSync(skill)) return true;
  if (!readFileSync(skill, "utf8").includes(SKILL_MARKER)) {
    out(`kept skill: ${skill} (not written by install-global)`);
    return true;
  }
  const ok = removeFile(skill, "skill", out);
  removeIfEmpty(skillDir);
  return ok;
}

function removeSettingsPermission(settingsPath: string, out: Out): boolean {
  if (!existsSync(settingsPath)) return true;
  try {
    const original = readFileSync(settingsPath, "utf8");
    const { removed, text } = removePermission(original);
    if (removed === 0) {
      if (original.includes("Bash(code-nav:*)")) out(`kept permission: Bash(code-nav:*) in ${settingsPath} (not valid JSON; remove it by hand)`);
      return true;
    }
    writeFileSync(settingsPath, text);
    out(`removed permission: Bash(code-nav:*) from ${settingsPath}`);
    return true;
  } catch (e) {
    out(`error: permission not removed from ${settingsPath} (${(e as Error).message})`);
    return false;
  }
}

export async function uninstall(argv: string[], out: Out): Promise<number> {
  const args = parseArgs(argv);
  if (args === null) {
    out(UNINSTALL_USAGE);
    return EXIT.error;
  }
  out(`daemons: ${await stopAllDaemons()} stopped`);
  const results = [
    remove(join(tmpdir(), "code-nav"), "daemon state and grammar configs", out),
    removeCache(out),
    removeFile(join(args.binDir, `code-nav${EXE_SUFFIX}`), "binary", out),
    removeSkill(join(args.claudeHome, "skills", "code-nav"), out),
    removeSettingsPermission(join(args.claudeHome, "settings.json"), out),
  ];
  out(`kept: crates fetched into ${cargoHome().path} by install rust-src`);
  out("next: bun remove -g code-nav");
  return results.every(Boolean) ? EXIT.success : EXIT.error;
}
