type Node =
  | { kind: "object"; start: number; end: number; members: { key: string; value: Node }[] }
  | { kind: "array"; start: number; end: number; items: Node[] }
  | { kind: "scalar"; start: number; end: number };

function parseSpans(text: string): Node {
  let i = 0;
  const skip = (): void => {
    while (i < text.length && /\s/.test(text[i]!)) i++;
  };
  const string = (): string => {
    const start = i++;
    while (text[i] !== '"') i += text[i] === "\\" ? 2 : 1;
    i++;
    return JSON.parse(text.slice(start, i)) as string;
  };
  const value = (): Node => {
    skip();
    const start = i;
    const c = text[i];
    if (c === "{") {
      i++;
      const members: { key: string; value: Node }[] = [];
      skip();
      while (text[i] !== "}") {
        if (text[i] === ",") i++;
        skip();
        const key = string();
        skip();
        i++;
        members.push({ key, value: value() });
        skip();
      }
      i++;
      return { kind: "object", start, end: i, members };
    }
    if (c === "[") {
      i++;
      const items: Node[] = [];
      skip();
      while (text[i] !== "]") {
        if (text[i] === ",") i++;
        items.push(value());
        skip();
      }
      i++;
      return { kind: "array", start, end: i, items };
    }
    if (c === '"') {
      string();
      return { kind: "scalar", start, end: i };
    }
    while (i < text.length && !/[\s,\]}]/.test(text[i]!)) i++;
    return { kind: "scalar", start, end: i };
  };
  return value();
}

function lineIndent(text: string, at: number): string {
  const lineStart = text.lastIndexOf("\n", at - 1) + 1;
  return /^[ \t]*/.exec(text.slice(lineStart))![0];
}

function indentUnit(text: string): string {
  return /\n([ \t]+)\S/.exec(text)?.[1] ?? "  ";
}

function insertMember(text: string, object: Node & { kind: "object" }, key: string, value: unknown): string {
  const multiline = text.includes("\n");
  const unit = indentUnit(text);
  const last = object.members.at(-1);
  if (!multiline) {
    const member = `${JSON.stringify(key)}:${JSON.stringify(value)}`;
    return last === undefined
      ? `${text.slice(0, object.start)}{${member}}${text.slice(object.end)}`
      : `${text.slice(0, last.value.end)},${member}${text.slice(last.value.end)}`;
  }
  const memberIndent = last === undefined ? lineIndent(text, object.start) + unit : lineIndent(text, last.value.start);
  const rendered = JSON.stringify(value, null, unit).split("\n").join(`\n${memberIndent}`);
  const member = `${JSON.stringify(key)}: ${rendered}`;
  if (last === undefined) {
    return `${text.slice(0, object.start)}{\n${memberIndent}${member}\n${lineIndent(text, object.start)}}${text.slice(object.end)}`;
  }
  return `${text.slice(0, last.value.end)},\n${memberIndent}${member}${text.slice(last.value.end)}`;
}

function appendItem(text: string, array: Node & { kind: "array" }, item: string): string {
  const literal = JSON.stringify(item);
  const last = array.items.at(-1);
  if (last === undefined) {
    if (!text.includes("\n")) return `${text.slice(0, array.start)}[${literal}]${text.slice(array.end)}`;
    const outer = lineIndent(text, array.start);
    return `${text.slice(0, array.start)}[\n${outer}${indentUnit(text)}${literal}\n${outer}]${text.slice(array.end)}`;
  }
  let separator: string;
  if (text.slice(array.start + 1, array.items[0]!.start).includes("\n")) separator = `,\n${lineIndent(text, last.start)}`;
  else if (array.items.length > 1) separator = text.slice(array.items[0]!.end, array.items[1]!.start);
  else separator = text.includes("\n") || /[,:] /.test(text) ? ", " : ",";
  return `${text.slice(0, last.end)}${separator}${literal}${text.slice(last.end)}`;
}

export type PermissionResult = "added" | "already present" | { invalid: string };

export function addPermission(text: string): { result: PermissionResult; text: string } {
  let parsed: unknown;
  try {
    parsed = JSON.parse(text);
  } catch {
    return { result: { invalid: "not valid JSON" }, text };
  }
  if (typeof parsed !== "object" || parsed === null || Array.isArray(parsed)) return { result: { invalid: "not a JSON object" }, text };
  const root = parseSpans(text);
  if (root.kind !== "object") return { result: { invalid: "not a JSON object" }, text };
  const permissions = root.members.findLast((m) => m.key === "permissions")?.value;
  if (permissions === undefined) return { result: "added", text: insertMember(text, root, "permissions", { allow: [PERMISSION] }) };
  if (permissions.kind !== "object") return { result: { invalid: '"permissions" is not an object' }, text };
  const allow = permissions.members.findLast((m) => m.key === "allow")?.value;
  if (allow === undefined) return { result: "added", text: insertMember(text, permissions, "allow", [PERMISSION]) };
  if (allow.kind !== "array") return { result: { invalid: '"permissions.allow" is not an array' }, text };
  const entries = (parsed as { permissions: { allow: unknown[] } }).permissions.allow;
  if (entries.includes(PERMISSION)) return { result: "already present", text };
  return { result: "added", text: appendItem(text, allow, PERMISSION) };
}

export function removePermission(text: string): { removed: number; text: string } {
  let removed = 0;
  for (;;) {
    let parsed: unknown;
    try {
      parsed = JSON.parse(text);
    } catch {
      return { removed, text };
    }
    const root = parseSpans(text);
    if (root.kind !== "object" || typeof parsed !== "object" || parsed === null) return { removed, text };
    const permissions = root.members.findLast((m) => m.key === "permissions")?.value;
    if (permissions?.kind !== "object") return { removed, text };
    const allow = permissions.members.findLast((m) => m.key === "allow")?.value;
    if (allow?.kind !== "array") return { removed, text };
    const at = allow.items.findIndex((item) => text.slice(item.start, item.end) === JSON.stringify(PERMISSION));
    if (at < 0) return { removed, text };
    const items = allow.items;
    if (items.length === 1) text = `${text.slice(0, allow.start)}[]${text.slice(allow.end)}`;
    else if (at === 0) text = `${text.slice(0, items[0]!.start)}${text.slice(items[1]!.start)}`;
    else text = `${text.slice(0, items[at - 1]!.end)}${text.slice(items[at]!.end)}`;
    removed++;
  }
}

export function installPermission(settingsPath: string): { line: string; ok: boolean } {
  mkdirSync(dirname(settingsPath), { recursive: true });
  if (!existsSync(settingsPath)) {
    writeFileSync(settingsPath, `${JSON.stringify({ permissions: { allow: [PERMISSION] } }, null, 2)}\n`);
    return { line: `permission: ${PERMISSION} added (created ${settingsPath})`, ok: true };
  }
  const { result, text } = addPermission(readFileSync(settingsPath, "utf8"));
  if (typeof result === "object") {
    return { line: `permission: ${PERMISSION} not added, ${settingsPath} left unchanged (${result.invalid})`, ok: false };
  }
  if (result === "added") writeFileSync(settingsPath, text);
  return { line: `permission: ${PERMISSION} ${result} in ${settingsPath}`, ok: true };
}

export async function stopAllDaemons(): Promise<number> {
  const stateRoot = join(tmpdir(), "code-nav");
  let entries: string[];
  try {
    entries = readdirSync(stateRoot);
  } catch {
    return 0;
  }
  let stopped = 0;
  for (const entry of entries) {
    if (entry === "grammars") continue;
    let root: unknown;
    try {
      root = (JSON.parse(readFileSync(join(stateRoot, entry, "daemon.json"), "utf8")) as { root?: unknown }).root;
    } catch {
      continue;
    }
    if (typeof root !== "string") continue;
    if ((await stop(root)) !== "no daemon running") stopped++;
  }
  return stopped;
}

export function installSkill(claudeHome: string): string {
  const skillDir = join(claudeHome, "skills", "code-nav");
  mkdirSync(skillDir, { recursive: true });
  const skillPath = join(skillDir, "SKILL.md");
  writeFileSync(skillPath, skillText(readFileSync(NOTE, "utf8")));
  return `skill: ${skillPath}`;
}
